local progress

describe("GitHub operation progress", function()
  before_each(function()
    progress = require("github.core.progress")
  end)
  after_each(function()
    vim.cmd("silent! %bwipeout!")
  end)
  it("shows loading or saving and never clears a newer operation with an older response", function()
    local buf = vim.api.nvim_get_current_buf()
    local old = progress.start(buf, "Loading...")
    assert.equals("Loading...", vim.b[buf].github_status)
    local saving = progress.start(buf, "Saving...")
    progress.finish(old)
    assert.equals("Saving...", vim.b[buf].github_status)
    local marks =
      vim.api.nvim_buf_get_extmarks(buf, vim.api.nvim_get_namespaces().github_progress, 0, -1, { details = true })
    assert.same({ { "Saving...", "Comment" } }, marks[1][4].virt_text)
    progress.finish(saving)
    assert.is_nil(vim.b[buf].github_status)
    assert.same({}, vim.api.nvim_buf_get_extmarks(buf, vim.api.nvim_get_namespaces().github_progress, 0, -1, {}))
  end)
end)
