describe("buffer request ownership", function()
  it("delivers reversed responses only to their original live buffers and drops stale responses", function()
    local request = require("github.core.request")
    local one = vim.api.nvim_create_buf(false, true)
    local two = vim.api.nvim_create_buf(false, true)
    local first, second = request.begin(one), request.begin(two)
    local newer = request.begin(one)
    assert.equals(
      true,
      request.apply(second, function(buf)
        vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "repo B" })
      end)
    )
    assert.equals(
      false,
      request.apply(first, function(buf)
        vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "stale" })
      end)
    )
    assert.equals(
      true,
      request.apply(newer, function(buf)
        vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "repo A" })
      end)
    )
    assert.same({ "repo A" }, vim.api.nvim_buf_get_lines(one, 0, -1, false))
    assert.same({ "repo B" }, vim.api.nvim_buf_get_lines(two, 0, -1, false))
    vim.api.nvim_buf_delete(one, { force = true })
    assert.equals(
      false,
      request.apply(newer, function()
        error("deleted buffer updated")
      end)
    )
    vim.api.nvim_buf_delete(two, { force = true })
  end)
  it("leaves edits made after save starts modified on success", function()
    local buffer = require("github.core.buffer")
    local buf = vim.api.nvim_create_buf(false, true)
    vim.bo[buf].buftype = "acwrite"
    vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "before" })
    local snapshot = buffer.begin_save(buf)
    assert.same({ "before" }, snapshot.lines)
    local again, err = buffer.begin_save(buf)
    assert.is_nil(again)
    assert.equals("save already in progress", err)
    vim.api.nvim_buf_set_lines(buf, 1, -1, false, { "after" })
    assert.equals(true, buffer.finish_save(snapshot, true))
    assert.same({ "before", "after" }, vim.api.nvim_buf_get_lines(buf, 0, -1, false))
    assert.equals(true, vim.bo[buf].modified)
    local next_snapshot = buffer.begin_save(buf)
    assert.equals(true, buffer.finish_save(next_snapshot, true))
    assert.equals(false, vim.bo[buf].modified)
    vim.api.nvim_buf_delete(buf, { force = true })
  end)
end)

describe("request lifecycle", function()
  it("drops requests after unload even if the buffer is loaded again", function()
    local request = require("github.core.request")
    local buf = vim.api.nvim_create_buf(true, false)
    local token = request.begin(buf)
    vim.api.nvim_buf_delete(buf, { unload = true, force = true })
    assert.is_false(request.apply(token, function()
      error("unloaded buffer updated")
    end))
    vim.fn.bufload(buf)
    assert.is_false(request.apply(token, function()
      error("reloaded buffer updated")
    end))
    local fresh = request.begin(buf)
    assert.is_true(request.apply(fresh, function(b)
      vim.api.nvim_buf_set_lines(b, 0, -1, false, { "fresh" })
    end))
    assert.same({ "fresh" }, vim.api.nvim_buf_get_lines(buf, 0, -1, false))
    vim.api.nvim_buf_delete(buf, { force = true })
  end)
end)

describe("concurrent GitHub requests", function()
  it("delivers reversed responses to the correct repository screen and ignores stale results", function()
    local request = require("github.core.request")
    local pending = {}
    local gh = require("github.core.gh").new(function(argv, opts, callback)
      table.insert(pending, { argv = argv, vars = vim.json.decode(opts.stdin).variables, callback = callback })
    end)
    local a = vim.api.nvim_create_buf(false, true)
    local b = vim.api.nvim_create_buf(false, true)
    local function start(buf, owner, repo)
      local token = request.begin(buf)
      gh.graphql(
        { host = "github.com", owner = owner, repo = repo },
        "query",
        { owner = owner, repo = repo },
        function(data)
          request.apply(token, function(target_buf)
            vim.api.nvim_buf_set_lines(target_buf, 0, -1, false, { data.data.repository.nameWithOwner })
          end)
        end
      )
    end
    start(a, "one", "alpha")
    start(b, "two", "beta")
    start(a, "one", "alpha")
    assert.same({ owner = "one", repo = "alpha" }, pending[1].vars)
    assert.same({ owner = "two", repo = "beta" }, pending[2].vars)
    pending[3].callback({ code = 0, stdout = '{"data":{"repository":{"nameWithOwner":"one/alpha"}}}' })
    pending[2].callback({ code = 0, stdout = '{"data":{"repository":{"nameWithOwner":"two/beta"}}}' })
    pending[1].callback({ code = 0, stdout = '{"data":{"repository":{"nameWithOwner":"old/alpha"}}}' })
    assert.same({ "one/alpha" }, vim.api.nvim_buf_get_lines(a, 0, -1, false))
    assert.same({ "two/beta" }, vim.api.nvim_buf_get_lines(b, 0, -1, false))
    vim.api.nvim_buf_delete(a, { force = true })
    vim.api.nvim_buf_delete(b, { force = true })
  end)
  it("drops callbacks for deleted and wiped buffers", function()
    local request = require("github.core.request")
    for _, wipe in ipairs({ false, true }) do
      local buf = vim.api.nvim_create_buf(true, false)
      local token = request.begin(buf)
      if wipe then
        vim.cmd("bwipeout! " .. buf)
      else
        vim.cmd("bdelete! " .. buf)
      end
      assert.is_false(request.apply(token, function()
        error("closed buffer updated")
      end))
    end
  end)
end)
